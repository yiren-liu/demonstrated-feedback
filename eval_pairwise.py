"""
Paper-style GPT-4 pairwise evaluation for the scenario experiment.

Mirrors the DITTO paper's evaluation methodology (Section 4.1, Appendix F):
  - Given an author-written reference text and two candidate texts (from
    different conditions), ask GPT-4 which candidate more closely matches
    the author's writing style.
  - Swap orderings and average to account for position bias.
  - Report head-to-head win rates.

All LLM judge calls run concurrently (controlled by --concurrency).

Usage:
    # Compare two specific generation files (same author, overlapping prompts)
    python eval_pairwise.py \
        --gen_a outputs/scenario_experiment/seen-s0-a0/generations.json \
        --gen_b outputs/scenario_experiment/unseen-is-a0/generations.json \
        --label_a seen --label_b unseen \
        --output_csv outputs/scenario_experiment/pairwise_seen-s0_vs_unseen-is_a0.csv

    # Batch: compare all seen vs unseen pairs automatically
    python eval_pairwise.py --batch \
        --results_dir outputs/scenario_experiment \
        --output_csv outputs/scenario_experiment/pairwise_results.csv

Environment:
    Set OPENAI_API_KEY before running.
"""

import argparse
import asyncio
import csv
import json
import os
import random
import sys
from collections import defaultdict

import numpy as np

try:
    import openai
except ImportError:
    print("ERROR: openai package required. Install with: pip install openai")
    sys.exit(1)


# ── GPT-4 pairwise evaluation prompt (following DITTO paper Appendix F) ──

PAIRWISE_PROMPT = """\
You are evaluating writing style similarity. You will be given:
1. A reference text written by a specific author.
2. Two candidate texts (A and B) generated by different systems.

Your task: determine which candidate text (A or B) more closely matches \
the writing style of the reference text. Consider tone, vocabulary, \
sentence structure, formality, and other stylistic features.

Reference text (by the author):
---
{reference}
---

Candidate A:
---
{candidate_a}
---

Candidate B:
---
{candidate_b}
---

Which candidate more closely matches the writing style of the reference? \
Answer with ONLY "A" or "B" (single letter, nothing else)."""


# ── Async OpenAI helpers ──

_aclient = None


def _get_aclient():
    global _aclient
    if _aclient is None:
        _aclient = openai.AsyncOpenAI()
    return _aclient


async def acall_gpt4(
    prompt: str,
    model: str = "gpt-4o",
    max_retries: int = 5,
    max_tokens: int = 1024,
) -> str:
    """Call OpenAI API asynchronously with exponential backoff retries."""
    client = _get_aclient()
    for attempt in range(max_retries):
        try:
            response = await client.chat.completions.create(
                model=model,
                messages=[{"role": "user", "content": prompt}],
                # max_completion_tokens=max_tokens,
                # temperature=0,
            )
            return response.choices[0].message.content.strip()
        except (openai.RateLimitError, openai.APIConnectionError) as e:
            wait = 2 ** attempt + random.random()
            print(f"  API error ({e}), retrying in {wait:.1f}s ...")
            await asyncio.sleep(wait)
        except Exception as e:
            print(f"  Unexpected API error: {e}")
            raise
    raise RuntimeError(f"Failed after {max_retries} retries")


# ── Progress tracker ──

class ProgressTracker:
    def __init__(self, total: int, label: str = ""):
        self.total = total
        self.done = 0
        self.label = label
        self._lock = asyncio.Lock()

    async def increment(self, msg: str = ""):
        async with self._lock:
            self.done += 1
            print(f"  [{self.done}/{self.total}] {self.label}{msg}")


# ── Core evaluation (async) ──

async def aevaluate_pair_pairwise(
    reference: str,
    gen_a: str,
    gen_b: str,
    model: str = "gpt-4o",
) -> dict:
    """
    Head-to-head pairwise comparison with order swapping.
    The two orderings (AB and BA) run concurrently.
    """
    prompt_ab = PAIRWISE_PROMPT.format(
        reference=reference, candidate_a=gen_a, candidate_b=gen_b,
    )
    prompt_ba = PAIRWISE_PROMPT.format(
        reference=reference, candidate_a=gen_b, candidate_b=gen_a,
    )

    # Run both orderings concurrently
    answer_ab, answer_ba = await asyncio.gather(
        acall_gpt4(prompt_ab, model=model),
        acall_gpt4(prompt_ba, model=model),
    )
    answer_ab = answer_ab.upper()
    answer_ba = answer_ba.upper()

    a_wins = 0
    b_wins = 0

    if "A" in answer_ab:
        a_wins += 1
    elif "B" in answer_ab:
        b_wins += 1

    if "A" in answer_ba:
        b_wins += 1
    elif "B" in answer_ba:
        a_wins += 1

    if a_wins > b_wins:
        winner = "a"
    elif b_wins > a_wins:
        winner = "b"
    else:
        winner = "tie"

    return {
        "answer_ab": answer_ab,
        "answer_ba": answer_ba,
        "a_wins": a_wins,
        "b_wins": b_wins,
        "winner": winner,
    }


# ── Single pair evaluation ──

def load_generations(path: str) -> dict:
    with open(path) as f:
        return json.load(f)


async def run_pairwise(
    gen_a_path: str,
    gen_b_path: str,
    label_a: str,
    label_b: str,
    output_csv: str,
    model: str = "gpt-4o",
    concurrency: int = 10,
) -> list:
    """
    Head-to-head pairwise evaluation between two generation files.
    All comparisons run concurrently up to the concurrency limit.
    """
    data_a = load_generations(gen_a_path)
    data_b = load_generations(gen_b_path)

    by_prompt_a = {item["prompt"]: item for item in data_a["results"] if item.get("reference")}
    by_prompt_b = {item["prompt"]: item for item in data_b["results"] if item.get("reference")}

    common_prompts = sorted(set(by_prompt_a.keys()) & set(by_prompt_b.keys()))

    if not common_prompts:
        print(f"No overlapping prompts between {gen_a_path} and {gen_b_path}.")
        print("Head-to-head pairwise comparison requires shared prompts.")
        return []

    # Collect all comparison tasks
    tasks = []
    for prompt_text in common_prompts:
        item_a = by_prompt_a[prompt_text]
        item_b = by_prompt_b[prompt_text]
        reference = item_a["reference"]

        n_gens = min(len(item_a["generations"]), len(item_b["generations"]))
        for gen_idx in range(n_gens):
            tasks.append({
                "prompt": prompt_text,
                "gen_idx": gen_idx,
                "reference": reference,
                "gen_a": item_a["generations"][gen_idx],
                "gen_b": item_b["generations"][gen_idx],
            })

    print(f"Found {len(common_prompts)} overlapping prompts, "
          f"{len(tasks)} comparisons (concurrency={concurrency})")
    print(f"  {label_a}: {gen_a_path}")
    print(f"  {label_b}: {gen_b_path}")

    sem = asyncio.Semaphore(concurrency)
    progress = ProgressTracker(len(tasks))

    async def eval_one(task):
        async with sem:
            result = await aevaluate_pair_pairwise(
                task["reference"], task["gen_a"], task["gen_b"], model=model,
            )
            await progress.increment(
                f"prompt='{task['prompt'][:50]}...' gen={task['gen_idx']} "
                f"winner={result['winner']}"
            )
            return {
                "label_a": label_a,
                "label_b": label_b,
                "prompt": task["prompt"][:80],
                "gen_idx": task["gen_idx"],
                **result,
            }

    rows = list(await asyncio.gather(*[eval_one(t) for t in tasks]))

    if rows:
        _write_csv(rows, output_csv)
        _print_winrate_summary(rows, label_a, label_b)

    return rows


# ── Batch evaluation ──

async def run_batch_pairwise(
    results_dir: str,
    output_csv: str,
    model: str = "gpt-4o",
    concurrency: int = 10,
):
    """
    Batch pairwise evaluation: for each author, compare seen vs each unseen
    condition. All comparisons across all author-pairs run concurrently.
    """
    # Discover generation files
    gen_files = {}
    for entry in sorted(os.listdir(results_dir)):
        gen_path = os.path.join(results_dir, entry, "generations.json")
        if os.path.isfile(gen_path):
            gen_files[entry] = gen_path

    # Group by author
    seen_by_author = {}
    unseen_by_author = defaultdict(list)

    for dirname, path in gen_files.items():
        parts = dirname.split("-")
        if parts[0] == "seen":
            author_id = parts[-1]
            seen_by_author[author_id] = (dirname, path)
        elif parts[0] == "unseen" or parts[0] == "single":
            author_id = parts[-1]
            variant = "-".join(parts[1:-1])
            unseen_by_author[author_id].append((dirname, path, variant))

    # Collect ALL comparison tasks across all author-condition pairs
    all_tasks = []
    for author_id in sorted(seen_by_author.keys()):
        if author_id not in unseen_by_author:
            continue

        seen_dirname, seen_path = seen_by_author[author_id]
        data_seen = load_generations(seen_path)
        by_prompt_seen = {
            item["prompt"]: item for item in data_seen["results"] if item.get("reference")
        }

        for unseen_dirname, unseen_path, variant in unseen_by_author[author_id]:
            data_unseen = load_generations(unseen_path)
            by_prompt_unseen = {
                item["prompt"]: item for item in data_unseen["results"] if item.get("reference")
            }

            common_prompts = sorted(set(by_prompt_seen.keys()) & set(by_prompt_unseen.keys()))
            if not common_prompts:
                print(f"No overlap: {seen_dirname} vs {unseen_dirname}")
                continue

            label_a = f"seen ({seen_dirname})"
            label_b = f"unseen-{variant} ({unseen_dirname})"

            for prompt_text in common_prompts:
                item_a = by_prompt_seen[prompt_text]
                item_b = by_prompt_unseen[prompt_text]
                reference = item_a["reference"]
                n_gens = min(len(item_a["generations"]), len(item_b["generations"]))

                for gen_idx in range(n_gens):
                    all_tasks.append({
                        "author": author_id,
                        "seen_dir": seen_dirname,
                        "unseen_dir": unseen_dirname,
                        "unseen_variant": variant,
                        "label_a": label_a,
                        "label_b": label_b,
                        "prompt": prompt_text,
                        "gen_idx": gen_idx,
                        "reference": reference,
                        "gen_a": item_a["generations"][gen_idx],
                        "gen_b": item_b["generations"][gen_idx],
                    })

    if not all_tasks:
        print("\nNo overlapping prompts found across any condition pairs.")
        return []

    print(f"\nTotal comparisons: {len(all_tasks)} (concurrency={concurrency})")

    sem = asyncio.Semaphore(concurrency)
    progress = ProgressTracker(len(all_tasks))

    async def eval_one(task):
        async with sem:
            result = await aevaluate_pair_pairwise(
                task["reference"], task["gen_a"], task["gen_b"], model=model,
            )
            await progress.increment(
                f"{task['seen_dir']} vs {task['unseen_dir']} "
                f"gen={task['gen_idx']} winner={result['winner']}"
            )
            return {
                "author": task["author"],
                "seen_dir": task["seen_dir"],
                "unseen_dir": task["unseen_dir"],
                "unseen_variant": task["unseen_variant"],
                "label_a": task["label_a"],
                "label_b": task["label_b"],
                "prompt": task["prompt"][:80],
                "gen_idx": task["gen_idx"],
                **result,
            }

    all_rows = list(await asyncio.gather(*[eval_one(t) for t in all_tasks]))

    if all_rows:
        fieldnames = [
            "author", "seen_dir", "unseen_dir", "unseen_variant",
            "label_a", "label_b", "prompt", "gen_idx",
            "answer_ab", "answer_ba", "a_wins", "b_wins", "winner",
        ]
        _write_csv(all_rows, output_csv, fieldnames=fieldnames)
        _print_batch_summary(all_rows)

    return all_rows


# ── Output helpers ──

def _write_csv(rows: list, output_csv: str, fieldnames: list = None):
    if not output_csv or not rows:
        return
    os.makedirs(os.path.dirname(output_csv) if os.path.dirname(output_csv) else ".", exist_ok=True)
    if fieldnames is None:
        fieldnames = list(rows[0].keys())
    with open(output_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)
    print(f"\nWrote {len(rows)} rows to {output_csv}")


def _print_winrate_summary(rows: list, label_a: str, label_b: str):
    wins = defaultdict(int)
    for r in rows:
        wins[r["winner"]] += 1
    total = len(rows)

    print(f"\n  {label_a} wins: {wins['a']}/{total} ({100*wins['a']/total:.1f}%)")
    print(f"  {label_b} wins: {wins['b']}/{total} ({100*wins['b']/total:.1f}%)")
    print(f"  Ties:            {wins['tie']}/{total} ({100*wins['tie']/total:.1f}%)")


def _print_batch_summary(rows: list):
    print(f"\n{'='*60}")
    print("BATCH SUMMARY: Pairwise win rates (paper-style)")
    print(f"{'='*60}")

    wins = defaultdict(int)
    for r in rows:
        wins[r["winner"]] += 1
    total = len(rows)
    print(f"\nOverall (n={total}):")
    print(f"  Seen wins:   {wins['a']}/{total} ({100*wins['a']/total:.1f}%)")
    print(f"  Unseen wins: {wins['b']}/{total} ({100*wins['b']/total:.1f}%)")
    print(f"  Ties:        {wins['tie']}/{total} ({100*wins['tie']/total:.1f}%)")

    by_variant = defaultdict(list)
    for r in rows:
        by_variant[r["unseen_variant"]].append(r)

    print(f"\nPer unseen variant:")
    print(f"  {'Variant':<20} {'Seen win%':>10} {'Unseen win%':>12} {'Tie%':>8} {'n':>5}")
    print(f"  {'-'*58}")
    for variant in sorted(by_variant.keys()):
        vrows = by_variant[variant]
        vwins = defaultdict(int)
        for r in vrows:
            vwins[r["winner"]] += 1
        vn = len(vrows)
        print(f"  {variant:<20} {100*vwins['a']/vn:>9.1f}% {100*vwins['b']/vn:>11.1f}% {100*vwins['tie']/vn:>7.1f}% {vn:>5}")

    by_author = defaultdict(list)
    for r in rows:
        by_author[r["author"]].append(r)

    print(f"\nPer author:")
    print(f"  {'Author':<8} {'Seen win%':>10} {'Unseen win%':>12} {'Tie%':>8} {'n':>5}")
    print(f"  {'-'*46}")
    author_seen_rates = []
    for author in sorted(by_author.keys()):
        arows = by_author[author]
        awins = defaultdict(int)
        for r in arows:
            awins[r["winner"]] += 1
        an = len(arows)
        seen_rate = awins["a"] / an if an > 0 else 0
        author_seen_rates.append(seen_rate)
        print(f"  {author:<8} {100*awins['a']/an:>9.1f}% {100*awins['b']/an:>11.1f}% {100*awins['tie']/an:>7.1f}% {an:>5}")

    if len(author_seen_rates) > 1:
        from scipy import stats
        t_stat, p_val = stats.ttest_1samp(author_seen_rates, 0.5)
        mean_rate = np.mean(author_seen_rates)
        sem = np.std(author_seen_rates, ddof=1) / np.sqrt(len(author_seen_rates))
        print(f"\n  Mean seen win rate: {100*mean_rate:.1f}% +/- {100*sem:.1f}%")
        print(f"  One-sample t-test (H0: win rate = 50%): t={t_stat:.3f}, p={p_val:.4f}")
        if p_val < 0.05:
            print("  => Significant difference (p < 0.05)")
        else:
            print("  => Not significant (p >= 0.05)")


# ── Main ──

def main():
    parser = argparse.ArgumentParser(
        description="Paper-style pairwise GPT-4 evaluation (head-to-head with order swapping)"
    )
    parser.add_argument("--batch", action="store_true",
                        help="Batch compare all seen vs unseen pairs in results_dir")
    parser.add_argument("--results_dir", type=str,
                        default="outputs/scenario_experiment",
                        help="Directory containing generation subdirectories")
    parser.add_argument("--gen_a", type=str,
                        help="Path to first generations.json")
    parser.add_argument("--gen_b", type=str,
                        help="Path to second generations.json")
    parser.add_argument("--label_a", type=str, default="A",
                        help="Label for first condition (e.g. 'seen')")
    parser.add_argument("--label_b", type=str, default="B",
                        help="Label for second condition (e.g. 'unseen')")
    parser.add_argument("--output_csv", type=str,
                        default="outputs/scenario_experiment/pairwise_results.csv",
                        help="Path to write pairwise results CSV")
    parser.add_argument("--model", type=str, default="gpt-4o",
                        help="OpenAI model for evaluation (default: gpt-4o)")
    parser.add_argument("--concurrency", type=int, default=10,
                        help="Max concurrent API calls (default: 10)")
    args = parser.parse_args()

    if args.batch:
        asyncio.run(run_batch_pairwise(
            args.results_dir, args.output_csv,
            model=args.model, concurrency=args.concurrency,
        ))
    elif args.gen_a and args.gen_b:
        asyncio.run(run_pairwise(
            args.gen_a, args.gen_b,
            args.label_a, args.label_b,
            args.output_csv,
            model=args.model, concurrency=args.concurrency,
        ))
    else:
        parser.error("Must specify either --batch or both --gen_a and --gen_b")


if __name__ == "__main__":
    main()
